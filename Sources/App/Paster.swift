import Cocoa

/// Inserts text into the focused field: clipboard + synthetic Cmd+V, then restores the clipboard.
enum Paster {
    static func insert(_ text: String) {
        let pb = NSPasteboard.general

        // Snapshot current clipboard (all items, all types).
        let saved: [[(NSPasteboard.PasteboardType, Data)]] = (pb.pasteboardItems ?? []).map { item in
            item.types.compactMap { t in item.data(forType: t).map { (t, $0) } }
        }

        pb.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        // Hint clipboard managers to ignore this entry.
        item.setString("", forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        item.setString("", forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        pb.writeObjects([item])
        let ourChange = pb.changeCount

        // Cmd+V (virtual key 9 = physical "V"; works with Russian layout too).
        let src = CGEventSource(stateID: .combinedSessionState)
        let vDown = CGEvent(keyboardEventSource: src, virtualKey: 9, keyDown: true)
        let vUp = CGEvent(keyboardEventSource: src, virtualKey: 9, keyDown: false)
        vDown?.flags = .maskCommand
        vUp?.flags = .maskCommand
        vDown?.post(tap: .cghidEventTap)
        vUp?.post(tap: .cghidEventTap)

        // Restore the previous clipboard once the target app has read it.
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.6) {
            guard pb.changeCount == ourChange else { return } // user copied something meanwhile
            pb.clearContents()
            if saved.isEmpty { return }
            let items: [NSPasteboardItem] = saved.map { pairs in
                let it = NSPasteboardItem()
                for (t, d) in pairs { it.setData(d, forType: t) }
                return it
            }
            pb.writeObjects(items)
        }
    }
}
