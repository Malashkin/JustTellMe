import Cocoa

/// Inserts text into the focused field: clipboard + synthetic Cmd+V, then restores the clipboard.
///
/// The text is put on the pasteboard as a lazy promise, so AppKit asks us for it at the moment
/// the target app actually reads it. That read is the receipt: shortly after it we put the
/// user's previous clipboard back. No fixed guess-the-delay, so slow apps (Electron, browsers)
/// don't end up pasting the old clipboard, and fast ones get it restored quickly.
final class Paster: NSObject, NSPasteboardItemDataProvider {
    static let shared = Paster()

    /// Markers from nspasteboard.org: clipboard managers (Maccy, Raycast, Paste…) skip such entries.
    private static let markers = ["org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType"]
        .map { NSPasteboard.PasteboardType($0) }

    private let pb = NSPasteboard.general
    private var text = ""
    private var pasted = false            // Cmd+V has been posted; reads from now on are the target app
    private var ourChange = 0
    private var saved: [[(NSPasteboard.PasteboardType, Data)]]?
    private var restoreWork: DispatchWorkItem?

    /// `sendKeys: false` only puts the text on the clipboard (used by the --demo-paste self-test).
    func insert(_ text: String, sendKeys: Bool = true) {
        // A previous paste is still waiting to restore: keep its snapshot (the user's real clipboard).
        if restoreWork == nil || saved == nil {
            saved = Prefs.restoreClipboard ? snapshot() : nil
        }
        restoreWork?.cancel()
        restoreWork = nil

        self.text = text
        pasted = false
        pb.clearContents()
        let item = NSPasteboardItem()
        if Prefs.restoreClipboard {
            item.setDataProvider(self, forTypes: [.string])
            for m in Self.markers { item.setString("", forType: m) }
        } else {
            item.setString(text, forType: .string)
        }
        pb.writeObjects([item])
        ourChange = pb.changeCount

        // Cmd+V (virtual key 9 = physical "V"; works with Russian layout too).
        if sendKeys { pressCmdV() }
        pasted = true

        // Fallback if no read receipt arrives (no text field focused, or something read it before ⌘V).
        if Prefs.restoreClipboard { scheduleRestore(after: 2.0) }
    }

    /// After a sentence end, add a space so the next dictation does not stick to it.
    static func withTrailingSpace(_ text: String) -> String {
        if let last = text.last, ".!?…".contains(last) { return text + " " }
        return text
    }

    /// Paste once the user has let go of the modifiers of the shortcut that triggered it (⌃⌥V):
    /// while they are held, the target app would receive ⌃⌥⌘V instead of ⌘V.
    func insertWhenModifiersReleased(_ text: String, deadline: Date = Date().addingTimeInterval(1.5)) {
        let held = CGEventSource.flagsState(.combinedSessionState).intersection([.maskControl, .maskAlternate, .maskShift, .maskCommand])
        if held.isEmpty || Date() > deadline { insert(text); return }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.03) { self.insertWhenModifiersReleased(text, deadline: deadline) }
    }

    private func pressCmdV() {
        let src = CGEventSource(stateID: .combinedSessionState)
        let vDown = CGEvent(keyboardEventSource: src, virtualKey: 9, keyDown: true)
        let vUp = CGEvent(keyboardEventSource: src, virtualKey: 9, keyDown: false)
        vDown?.flags = .maskCommand
        vUp?.flags = .maskCommand
        vDown?.post(tap: .cghidEventTap)
        vUp?.post(tap: .cghidEventTap)
    }

    // MARK: NSPasteboardItemDataProvider

    func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType) {
        item.setString(text, forType: type)
        if pasted { scheduleRestore(after: 0.25) }
    }

    // MARK: -

    private func scheduleRestore(after delay: TimeInterval) {
        restoreWork?.cancel()
        let work = DispatchWorkItem { [weak self] in self?.restore() }
        restoreWork = work
        DispatchQueue.main.asyncAfter(deadline: .now() + delay, execute: work)
    }

    private func restore() {
        restoreWork = nil
        defer { saved = nil }
        guard pb.changeCount == ourChange, let saved else { return } // user copied something meanwhile
        pb.clearContents()
        if saved.isEmpty { return }
        pb.writeObjects(saved.map { pairs in
            let it = NSPasteboardItem()
            for (t, d) in pairs { it.setData(d, forType: t) }
            return it
        })
    }

    /// All items, all types of the current clipboard.
    private func snapshot() -> [[(NSPasteboard.PasteboardType, Data)]] {
        (pb.pasteboardItems ?? []).map { item in
            item.types.compactMap { t in item.data(forType: t).map { (t, $0) } }
        }
    }
}
